
let _keyMem = null; // fallback if storage is blocked (sandboxed iframe)
function getKey(){ try{ return sessionStorage.getItem('reforge_api_key') || _keyMem; } catch(e){ return _keyMem; } }
function saveKey(){
  const v = document.getElementById('apiKeyInput').value.trim();
  if (!v) return;
  try { sessionStorage.setItem('reforge_api_key', v); } catch(e){ _keyMem = v; }
  renderContent();
}
function removeKey(){ try { sessionStorage.removeItem('reforge_api_key'); } catch(e){} _keyMem = null; renderContent(); }

// ── AI engine (opt-in): deterministic-first pipeline, grounded, never simulated ──
// 1. CONTEXT: deterministic extract — entity, evidence (file+line+note),
//    direct upstream/downstream neighbors with confidence, unknown areas/warnings. Facts only.
// 2. GUARDRAIL: the prompt requires answering ONLY from the context, citing
//    the evidence, stating "unknown" otherwise — never invent names/dependencies.
// 3. KEY/ENDPOINT: local sessionStorage, never in the prompt nor the telemetry.
// 4. CALL: only if configured; otherwise offline deterministic mode.
// 5. DISPLAY: any AI response is labeled "AI-proposed", never merged
//    with the deterministic output.
function aiCfg(){
  try { return { url: (sessionStorage.getItem('reforge_ai_url') || '').trim(),
    model: (sessionStorage.getItem('reforge_ai_model') || '').trim(), key: getKey() || '' }; }
  catch(e){ return { url: '', model: '', key: '' }; }
}
function aiReady(){ const c = aiCfg(); return !!(c.url && c.key); }
function aiSaveCfg(){
  try {
    const u = document.getElementById('aiUrlInput'), mo = document.getElementById('aiModelInput');
    if (u && u.value.trim()) sessionStorage.setItem('reforge_ai_url', u.value.trim()); else sessionStorage.removeItem('reforge_ai_url');
    if (mo && mo.value.trim()) sessionStorage.setItem('reforge_ai_model', mo.value.trim()); else sessionStorage.removeItem('reforge_ai_model');
  } catch(e){}
  renderContent();
}
function buildAiContext(m, id){
  const n = m && m.nodes && m.nodes.get ? m.nodes.get(id) : null;
  if (!n) return null;
  const imp = impact(m, id);
  const evOf = e => (e.ev || []).slice(0, 3).map(x => (x.file || '?') + (x.ln != null ? ' L' + x.ln : '') + ' — ' + x.note);
  return {
    entity: { id: n.id, type: n.type, name: n.name, data: n.data || {} },
    upstream: (imp.up.direct || []).slice(0, 8).map(r => ({ id: r.id, conf: r.conf, evidence: evOf(r.edge) })),
    downstream: (imp.down.direct || []).slice(0, 8).map(r => ({ id: r.id, conf: r.conf, evidence: evOf(r.edge) })),
    modelCoverage: { nodes: m.nodes.size, edges: m.edges.length,
      unknowns: (m.warnings || []).slice(0, 12) }
  };
}
function buildAiPrompt(ctx){
  return {
    system: 'You are a mainframe (JCL/COBOL) code analyst. Answer ONLY from the provided context. Cite the evidence lines you use (file + line + note). If something is not in the context, state explicitly that it is unknown — never invent program names, datasets, tables, JCL steps or dependencies. Respect the confidence labels (certain/probable/unknown). Your output is a PROPOSAL for a human analyst, not ground truth.',
    user: 'Analyze this entity extracted by a deterministic analysis engine (facts + evidence only; nothing else is known):\n\n' + JSON.stringify(ctx, null, 1)
  };
}
async function aiExplain(id){
  const c = aiCfg();
  if (!c.url || !c.key) return { source: 'deterministic', reason: 'AI endpoint/key not configured — offline deterministic mode' };
  const m = getModel();
  const ctx = buildAiContext(m, id || state.entity);
  if (!ctx) return { source: 'deterministic', reason: 'entity not found' };
  const p = buildAiPrompt(ctx);
  let res;
  try {
    res = await window.fetch(c.url, { method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Authorization': 'Bearer ' + c.key },
      body: JSON.stringify({ model: c.model || 'default', temperature: 0,
        messages: [{ role: 'system', content: p.system }, { role: 'user', content: p.user }] }) });
  } catch(e){ return { source: 'deterministic', reason: 'API unreachable: ' + e.message }; }
  if (!res || !res.ok) return { source: 'deterministic', reason: 'API HTTP ' + (res ? res.status : 'error') };
  let j = null;
  try { j = await res.json(); } catch(e){}
  const txt = j && j.choices && j.choices[0] && j.choices[0].message && j.choices[0].message.content;
  if (!txt) return { source: 'deterministic', reason: 'unexpected API response shape' };
  return { source: 'ai', model: c.model || 'default', text: txt, context: ctx };
}
function aiBannerHtml(source, extra){
  return source === 'ai'
    ? `<p class="note" style="color:var(--yellow)">✦ <b>AI-PROPOSED</b> — generated by ${esc(extra || 'the configured model')} from cited evidence. Verify before use: this is a proposal, never ground truth. Deterministic facts remain in the other views.</p>`
    : `<p class="note" style="color:var(--green)">⚙ Deterministic mode (offline) — ${esc(extra || 'AI not configured')}. No AI output is shown because none is produced.</p>`;
}

// ── Ask the graph: deterministic Q&A, fully offline, no LLM ──
// The question is parsed by keyword patterns; the target entity is matched
// LITERALLY against model node names (nothing guessed); every answer line is
// derived from one real edge with its confidence and file:line evidence.
// Unknown entity, ambiguous match or unsupported question → explicit honest
// refusal. This is NOT a free-form chat: the supported question types are
// listed in the refusal message.
function aiFindEntity(q){
  const m = getModel();
  const ql = String(q || '').toLowerCase();
  const hits = [];
  m.nodes.forEach(n => {
    const nm = String(n.name || '').toLowerCase();
    if (nm.length >= 3 && ql.includes(nm)) hits.push(n);
  });
  return hits;
}
function aiAsk(q){
  if (!state.loaded) return { ok: false, reason: 'no analysis loaded — run the analysis first' };
  const m = getModel();
  const ql = String(q || '').toLowerCase().trim();
  if (!ql) return { ok: false, reason: 'empty question' };
  const hits = aiFindEntity(q);
  if (!hits.length)
    return { ok: false, reason: 'no entity of this analysis matches the question — names are matched literally from the loaded files, nothing is guessed' };
  let n = hits[0];
  if (hits.length > 1){
    const exact = hits.find(x => ql.includes(String(x.id).toLowerCase()));
    if (!exact)
      return { ok: false, ambiguous: hits.map(x => x.id), reason: 'several entities match — specify which one (a name or type|name)' };
    n = exact;
  }
  const isIo   = /(who|what|which)\b/.test(ql) && /(read|write|writes|reads|written|updated?|updated by)/.test(ql);
  const isHist = /(what (has )?chang|diff|history|evolution|since (version|v\d|the )?)/.test(ql);
  const isImp  = /(impact|break|if i (modify|change|delete|touch))/.test(ql);
  const isLin  = /(lineage|origin|where does .* come from|where is .* from|trace)/.test(ql);
  const isUse  = /(who|what) (calls|uses|runs)|\b(calls|uses) \b/.test(ql);
  const intent = isIo ? 'io' : isHist ? 'history' : isImp ? 'impact' : isLin ? 'lineage' : isUse ? 'uses' : null;
  if (!intent)
    return { ok: false, reason: 'unsupported question — I can answer, offline and from the graph only: who reads/writes a dataset · who calls/uses an entity · impact of modifying an entity · lineage of a dataset · what changed between versions' };
  const fmtEv = e => (e.ev && e.ev[0]) ? ((e.ev[0].file || '?') + (e.ev[0].ln != null ? ':' + e.ev[0].ln : '')) : null;
  if (intent === 'history'){
    const H = state.history;
    if (H.length < 2)
      return { ok: true, intent, entity: n.id, lines: [{ text: 'Only ' + H.length + ' snapshot(s) recorded — no evolution to report yet.', c: 'certain' }] };
    const a = H[H.length - 2], b = H[H.length - 1];
    const d = graphDiff(a, b);
    const lines = [];
    d.nodesAdded.forEach(x => lines.push({ text: '+ entity ' + x.id, c: 'certain' }));
    d.nodesRemoved.forEach(x => lines.push({ text: '− entity ' + x.id, c: 'certain' }));
    d.edgesAdded.forEach(k => lines.push({ text: '+ relation ' + k.split('|').slice(0, -1).join(' —') + '→ (' + k.split('|').pop() + ')', c: 'certain' }));
    d.edgesRemoved.forEach(k => lines.push({ text: '− relation ' + k.split('|').slice(0, -1).join(' —') + '→ (' + k.split('|').pop() + ')', c: 'certain' }));
    if (d.filesChanged.length) lines.push({ text: 'files changed: ' + d.filesChanged.join(', '), c: 'certain' });
    if (!lines.length) lines.push({ text: 'No model change between ' + a.label + ' and ' + b.label + '.', c: 'certain' });
    return { ok: true, intent, entity: n.id, lines, note: 'last two snapshots compared (' + a.label + ' → ' + b.label + ')' };
  }
  const outE = m.fwd[n.id] || [], inE = m.rev[n.id] || [];
  const lines = [];
  if (intent === 'io'){
    const io = [...outE, ...inE].filter(e => e.k === 'read' || e.k === 'write');
    io.forEach(e => {
      const isOut = outE.includes(e);
      const other = isOut ? e.t : e.f;
      lines.push({ text: (isOut ? (e.k === 'write' ? 'writes to ' : 'reads from ') : (e.k === 'write' ? 'is written by ' : 'is read by ')) + other, c: e.c, ev: fmtEv(e) });
    });
    if (!lines.length) lines.push({ text: 'No direct I/O relation found for this entity in the graph.', c: 'unknown' });
  } else if (intent === 'uses'){
    inE.forEach(e => lines.push({ text: 'used by ' + e.f + ' (' + e.k + ')', c: e.c, ev: fmtEv(e) }));
    if (!lines.length) lines.push({ text: 'No incoming usage relation found — nothing in this analysis references it.', c: 'unknown' });
  } else { // impact / lineage — one hop each direction, honestly stated
    inE.forEach(e => lines.push({ text: 'upstream: ' + e.f + ' (' + e.k + ')', c: e.c, ev: fmtEv(e) }));
    outE.forEach(e => lines.push({ text: 'downstream: ' + e.t + ' (' + e.k + ')', c: e.c, ev: fmtEv(e) }));
    if (!lines.length) lines.push({ text: 'No relation found for this entity — it is isolated in the current analysis.', c: 'unknown' });
    if (intent === 'impact') lines.push({ text: 'One hop only — transitive impact is not expanded here; use the Impact view for the full walk.', c: 'certain' });
  }
  return { ok: true, intent, entity: n.id, lines };
}
function aiAskRun(){
  const inp = document.getElementById('aiQInput');
  const out = document.getElementById('aiQOut');
  if (!inp || !out) return;
  const q = inp.value || '';
  const r = aiAsk(q);
  const confColor = { certain: 'var(--green)', probable: 'var(--yellow)', unknown: 'var(--text3)' };
  let body;
  if (!r.ok){
    const amb = r.ambiguous ? `<p>${r.ambiguous.map(a => `<span class="mono pill" style="border:1px solid var(--text3)">${esc(a)}</span>`).join(' ')}</p>` : '';
    body = `<p class="note" style="color:var(--yellow)">⚠ ${esc(r.reason)}</p>${amb}`;
  } else {
    const lines = r.lines.map(l =>
      `<div class="log"><span style="color:${confColor[l.c] || confColor.unknown};font-weight:bold">${esc(l.c)}</span> ${esc(l.text)}${l.ev ? ` <span class="note">(${esc(l.ev)})</span>` : ''}</div>`).join('');
    body = `<p class="note" style="color:var(--green)">⚙ Deterministic answer — derived only from graph edges of <span class="mono">${esc(r.entity)}</span>${r.note ? ' · ' + esc(r.note) : ''}</p>${lines}`;
  }
  out.innerHTML = body;
  track('ai_ask');
}
async function aiRun(){
  const out = document.getElementById('aiOut');
  if (out) out.innerHTML = '<p class="note">Calling model…</p>';
  let r;
  try { r = await aiExplain(state.entity); }
  catch(e){ r = { source: 'deterministic', reason: 'error: ' + e.message }; }
  const body = r.source === 'ai'
    ? `<div style="white-space:pre-wrap;font-family:var(--mono);font-size:12px;line-height:1.6;background:var(--bg2);border:1px solid var(--line);padding:12px;border-radius:8px">${esc(r.text)}</div>`
    : `<p class="note">${esc(r.reason || '')}</p>`;
  if (out) out.innerHTML = aiBannerHtml(r.source, r.source === 'ai' ? r.model : r.reason) + body;
}
